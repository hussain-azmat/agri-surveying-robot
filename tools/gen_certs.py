#!/usr/bin/env python3
"""Regenerate firmware/agri_rover/certs.h: the trusted root CAs for GitHub TLS.

The rover never uses insecure TLS. It validates api.github.com against the roots embedded
here. GitHub changes certificate authorities from time to time (api.github.com currently
chains to USERTrust ECC via Sectigo; other GitHub hosts use Let's Encrypt/ISRG or DigiCert),
so we embed a deliberate SET of long-lived roots, and tools/check_tls_roots.py (run weekly by
CI) fails loudly BEFORE a CA change could ever stop OTA updates from working.

Usage:
    python tools/gen_certs.py <ca-bundle.pem>
    e.g. the Mozilla bundle from curl (https://curl.se/ca/cacert.pem), certifi, or Git for Windows:
    python tools/gen_certs.py "C:/Program Files/Git/mingw64/etc/ssl/certs/ca-bundle.crt"
"""
import re
import sys
from pathlib import Path

# Roots GitHub has used or plausibly will use. Add to this list rather than removing from it.
WANTED = [
    "USERTrust ECC Certification Authority",
    "USERTrust RSA Certification Authority",
    "Sectigo Public Server Authentication Root E46",
    "Sectigo Public Server Authentication Root R46",
    "ISRG Root X1",
    "ISRG Root X2",
    "DigiCert Global Root G2",
    "DigiCert Global Root CA",
    "DigiCert TLS ECC P384 Root G5",
    "DigiCert TLS RSA4096 Root G5",
]

SKIP_PREFIXES = ("Issuer:", "Subject:", "Serial", "MD5", "SHA1", "SHA256", "Not Valid", "Label:", "Fingerprint")


def parse_bundle(text):
    """Returns {label: pem}. Understands the curl/Git style ('# Name') and certifi style ('# Label: "Name"')."""
    certs = {}
    label = None
    pem = None
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("# Label:"):
            m = re.search(r'"(.+)"', s)
            label = m.group(1) if m else label
        elif s.startswith("#") and not s.lstrip("# ").startswith(SKIP_PREFIXES) and not s.startswith("##"):
            candidate = s.lstrip("# ").strip()
            if candidate:
                label = candidate
        elif s == "-----BEGIN CERTIFICATE-----":
            pem = [s]
        elif s == "-----END CERTIFICATE-----" and pem is not None:
            pem.append(s)
            if label:
                certs[label] = "\n".join(pem) + "\n"
            pem = None
        elif pem is not None:
            pem.append(s)
    return certs


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    bundle = parse_bundle(Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace"))
    missing = [w for w in WANTED if w not in bundle]
    if missing:
        print("ERROR: not found in the bundle: " + ", ".join(missing), file=sys.stderr)
        return 1

    out = Path(__file__).resolve().parent.parent / "firmware" / "agri_rover" / "certs.h"
    lines = [
        "#pragma once",
        "// GENERATED by tools/gen_certs.py: do not edit by hand.",
        "// Trusted root CAs for GitHub TLS (public certificates, not secrets). See that script for why this is a set.",
        "// ~%d certificates. Verify with: python tools/check_tls_roots.py" % len(WANTED),
        "",
        "static const char GITHUB_ROOT_CAS[] =",
    ]
    for name in WANTED:
        lines.append('    // %s' % name)
        for pem_line in bundle[name].strip().splitlines():
            lines.append('    "%s\\n"' % pem_line)
    lines[-1] += ";"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote %s (%d certificates, %d bytes of PEM)" % (out, len(WANTED), sum(len(bundle[w]) for w in WANTED)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
